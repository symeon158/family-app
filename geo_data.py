def make_map_question(entity_list, prompt_fn, center, zoom, key_field="name", n_opts=4, exclude_names=None):
    """Φτιάχνει ΤΥΧΑΙΑ μια ερώτηση τύπου 'χάρτης' από μια λίστα οντοτήτων.

    Το exclude_names αποφεύγει να ξαναβγεί ως ΣΩΣΤΗ απάντηση μια οντότητα που έχει ήδη
    ρωτηθεί μέσα στο ίδιο κουίζ. Οι λανθασμένες επιλογές (distractors) μπορούν πάντα να
    ξαναχρησιμοποιηθούν, ώστε να μη στερέψει η δεξαμενή ακόμη κι όταν είναι μικρή."""
    pool = list(entity_list)
    correct_candidates = [e for e in pool if not exclude_names or e["name"] not in exclude_names]
    if not correct_candidates:
        correct_candidates = pool
    correct_entity = random.choice(correct_candidates)
    others = [e for e in pool if e is not correct_entity]
    random.shuffle(others)
    # Οι πινέζες δεν πρέπει να πέφτουν η μία πάνω στην άλλη (περίπου 34 pixel σε αυτό το zoom).
    min_km = 34 * 120 / 2 ** zoom
    chosen = [correct_entity]
    for e in others:
        if len(chosen) < n_opts and all(distance_km(e["lat"], e["lon"], c["lat"], c["lon"]) >= min_km for c in chosen):
            chosen.append(e)
    chosen += [e for e in others if e not in chosen][:n_opts - len(chosen)]
    random.shuffle(chosen)
    correct_idx = chosen.index(correct_entity)
    return {
        "q": prompt_fn(correct_entity),
        "type": "map", "center": center, "zoom": zoom, "correct": correct_idx,
        "opts": [{"name": e[key_field], "lat": e["lat"], "lon": e["lon"]} for e in chosen],
        "fact": correct_entity.get("fact", ""),
    }


