def distance_km(lat1, lon1, lat2, lon2):
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(a))


def bearing_deg(lat1, lon1, lat2, lon2):
    """Η κατεύθυνση όπως φαίνεται πάνω στον χάρτη (0 = Βορράς, 90 = Ανατολή)."""
    dx = (lon2 - lon1) * math.cos(math.radians((lat1 + lat2) / 2))
    return math.degrees(math.atan2(dx, lat2 - lat1)) % 360


def direction_name(lat1, lon1, lat2, lon2):
    return DIRECTIONS[round(bearing_deg(lat1, lon1, lat2, lon2) / 45) % 8]


def find_targets(n):
    """Στόχοι για το «Ζεστά-Κρύα», με διαφορετικά ονόματα (π.χ. η Κέρκυρα είναι και πόλη και νησί)."""
    pool = [dict(e, kind=k) for k in KIND_LABEL for e in ENTITIES_BY_KIND[k]]
    random.shuffle(pool)
    picked, names = [], set()
    for e in pool:
        if e["name"] not in names:
            names.add(e["name"])
            picked.append(e)
    return picked[:n]


